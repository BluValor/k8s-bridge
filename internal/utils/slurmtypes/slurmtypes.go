package slurmtypes

import (
	"k8s.io/apimachinery/pkg/types"
)

// SlurmJobAdmissionEvent represents an event generated by the SlurmPoller
// when a pending Slurm job is discovered that matches a configured partition.
type SlurmJobAdmissionEvent struct {
	// JobID is the unique identifier of the Slurm job.
	JobID string
	// RawJobSpecJSON is the serialized JSON representation of the full Slurm job specification.
	RawJobSpecJSON string
	// WorkloadMixing is the NamespacedName of the WorkloadMixing CR that configured this query.
	WorkloadMixing types.NamespacedName
}

// SlurmJobTeardownEvent represents an event generated by the SlurmPoller
// when a Slurm job reaches a terminal state or is identified as orphaned.
type SlurmJobTeardownEvent struct {
	// JobID is the unique identifier of the Slurm job.
	JobID string
	// WorkloadMixing is the NamespacedName of the parent WorkloadMixing CR.
	WorkloadMixing types.NamespacedName
	// Partition is the Slurm partition associated with the workload.
	Partition string
	// Reason indicates the reason for teardown.
	Reason string
}
